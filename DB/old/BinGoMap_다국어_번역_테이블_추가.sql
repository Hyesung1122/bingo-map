-- 1. 지원 언어 목록
CREATE TABLE SUPPORTED_LANGUAGES (
    LOCALE_CODE         VARCHAR2(10)    NOT NULL,
    DISPLAY_NAME        VARCHAR2(40)    NOT NULL,
    IS_ENABLED          CHAR(1)         DEFAULT 'Y' NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SUPPORTED_LANGUAGES PRIMARY KEY (LOCALE_CODE),
    CONSTRAINT CK_SUPPORTED_LANG_ENABLED CHECK (IS_ENABLED IN ('Y', 'N'))
);

