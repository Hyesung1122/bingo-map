-- 2. 식당 번역
CREATE TABLE RESTAURANT_TRANSLATIONS (
    RESTAURANT_ID       NUMBER(19)      NOT NULL,
    LOCALE_CODE         VARCHAR2(10)    NOT NULL,
    SOURCE_LOCALE_CODE  VARCHAR2(10),
    NAME                VARCHAR2(500)   NOT NULL,
    CATEGORY            VARCHAR2(500),
    TAGS                VARCHAR2(1000),
    DESCRIPTION         CLOB,
    ADDRESS             VARCHAR2(4000),
    OPENING_HOURS       VARCHAR2(2000),
    SEAT_INFO           VARCHAR2(300),
    RESERVATION_INFO    VARCHAR2(300),
    PAYMENT_METHODS     VARCHAR2(600),
    LANGUAGES_LABEL     VARCHAR2(600),
    MENU_NAME           VARCHAR2(500),
    MENU_DESCRIPTION    CLOB,
    TRANSLATION_STATUS  VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESTAURANT_TRANS PRIMARY KEY (RESTAURANT_ID, LOCALE_CODE),
    CONSTRAINT FK_REST_TRANS_RESTAURANT FOREIGN KEY (RESTAURANT_ID)
        REFERENCES RESTAURANTS (RESTAURANT_ID),
    CONSTRAINT FK_REST_TRANS_LOCALE FOREIGN KEY (LOCALE_CODE)
        REFERENCES SUPPORTED_LANGUAGES (LOCALE_CODE),
    CONSTRAINT FK_REST_TRANS_SOURCE FOREIGN KEY (SOURCE_LOCALE_CODE)
        REFERENCES SUPPORTED_LANGUAGES (LOCALE_CODE),
    CONSTRAINT CK_REST_TRANS_STATUS
        CHECK (TRANSLATION_STATUS IN ('PENDING', 'MACHINE_DRAFT', 'REVIEWED'))
);

